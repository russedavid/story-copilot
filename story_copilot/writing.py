"""Writing guidance for usable private drafts, independent of model selection."""

FACILITATOR_WRITING = """
Make the response something the facilitator can use at the table now.
For an NPC question, supply the NPC's actual reply, with a specific concern or intention drawn from the scene.
For a confirmed player action, give one clear world reaction and leave the next player choice open.
Consistent new NPC dialogue or small world details are welcome as creative proposals. Do not invent a
completed player action, reveal a protected secret, resolve an uncertain check, or manufacture a rule.
Usually one short paragraph of narration is enough; follow an explicitly requested longer style when given.
Prefer concrete actions and plain speech. One telling sensory detail is stronger than a catalogue of atmosphere.
Avoid rephrasing the player's contribution, recapping the whole scene, generic suspense, and menus of unrelated possibilities.
Answer an outstanding question before adding a new complication. Do not make every NPC evasive by default.
Do not finish with a stock 'What do you do?' when the situation already invites a response.
Keep bookkeeping in direct_answer and actual private reminders in private_notes; omit empty or redundant commentary.
The draft should not discuss tools, context packing, source validation, or the fact that it is an AI suggestion.
"""

PLAYER_WRITING = """
Make a contribution another participant can naturally respond to. Connect it to the last exchange.
Let the supplied personality change what you attend to and choose, rather than announcing the personality.
Use the assigned character's goals, knowledge, and equipment. Usually one to three sentences suffice.
A curious player asks a concrete, useful question or tests a visible possibility; avoid a checklist of observations.
A decisive player proposes a bounded next step with a clear purpose; leave others free to accept or decline cooperation.
Speak naturally in the character's voice. Avoid generic preambles, repeated 'I want to inspect' phrasing,
invented certainty, or narrating a whole sequence of outcomes. Uncertain results belong to the facilitator.
"""
